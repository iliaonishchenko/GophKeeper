/*
Package gophkeeper реализует клиент-серверный менеджер секретов GophKeeper.

Система позволяет пользователю надёжно хранить пары логин/пароль, произвольные
текстовые и бинарные данные, а также данные банковских карт. Шифрование происходит
на стороне клиента: сервер хранит только шифртекст и не имеет доступа к
мастер паролю или нешифрованным данным.

Проект состоит из двух компонентов:

Сервер (cmd/server) принимает запросы по gRPC, хранит шифрованные данные в
Postgre и синхронизирует их между несколькими авторизованными клиентами
одного владельца.

Клиент (cmd/client) — кроссплатформенное CLI-приложение, выполняющее регистрацию
и аутентификацию пользователя, шифрование данных перед отправкой и расшифровку
полученных данных.

Основные внутренние пакеты:

  - internal/proto — сгенерированный код gRPC-сервиса Keeper.
  - internal/grpcserver — реализация gRPC-сервиса и перехватчик авторизации.
  - internal/service — бизнес-логика (регистрация, аутентификация, хранилище).
  - internal/repository — слой доступа к PostgreSQL.
  - internal/model — доменные модели (User, Item).
  - internal/crypto — PBKDF2-деривация ключей и AES-256-GCM шифрование.
  - internal/signature — HMAC-SHA256 подпись данных.
  - internal/token — выпуск и проверка bearer-токенов авторизации.
  - internal/clientapp — бизнес-логика клиента (сессия, шифрование, синхронизация).
  - internal/config — конфигурация сервера и клиента.
  - internal/logger — структурированное логирование.
*/
package gophkeeper
